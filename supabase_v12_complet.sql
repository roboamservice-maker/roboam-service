-- ROBOAM SERVICE V7 : schéma de départ
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text,
 phone text,
 created_at timestamptz default now()
);

create table if not exists public.categories (
 id bigint generated by default as identity primary key,
 name text unique not null
);

create table if not exists public.products (
 id bigint generated by default as identity primary key,
 category_id bigint references public.categories(id),
 name text not null,
 description text,
 unit text,
 brand text,
 variant text,
 price numeric(12,2) not null default 0,
 stock integer not null default 0,
 active boolean not null default true,
 created_at timestamptz default now()
);

create table if not exists public.orders (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 status text not null default 'reçue',
 total numeric(12,2) not null default 0,
 delivery_address text,
 phone text,
 payment_method text,
 created_at timestamptz default now()
);

create table if not exists public.order_items (
 id bigint generated by default as identity primary key,
 order_id bigint not null references public.orders(id) on delete cascade,
 product_id bigint references public.products(id),
 product_name text not null,
 quantity integer not null,
 unit_price numeric(12,2) not null
);

alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists "public categories read" on public.categories;
create policy "public categories read" on public.categories for select using (true);
drop policy if exists "public active products read" on public.products;
create policy "public active products read" on public.products for select using (active=true);
drop policy if exists "users own orders read" on public.orders;
create policy "users own orders read" on public.orders for select using (auth.uid()=user_id);
drop policy if exists "users own orders insert" on public.orders;
create policy "users own orders insert" on public.orders for insert with check (auth.uid()=user_id);
drop policy if exists "users own order items read" on public.order_items;
create policy "users own order items read" on public.order_items for select using (
 exists(select 1 from public.orders o where o.id=order_id and o.user_id=auth.uid())
);

-- Crée automatiquement le profil à l'inscription
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
begin
 insert into public.profiles(id,full_name) values(new.id,new.raw_user_meta_data->>'full_name');
 return new;
end; $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();
