create policy "payments own read" on public.payment_transactions for select using (auth.uid()=user_id);
create policy "payments own insert" on public.payment_transactions for insert with check (auth.uid()=user_id);
create policy "admin payments read" on public.payment_transactions for select using (exists(select 1 from public.admin_users where user_id=auth.uid()));
create policy "admin payments update" on public.payment_transactions for update using (exists(select 1 from public.admin_users where user_id=auth.uid()));

create index if not exists payment_transactions_order_idx on public.payment_transactions(order_id);
create index if not exists payment_transactions_provider_ref_idx on public.payment_transactions(provider_reference);

