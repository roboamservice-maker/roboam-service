-- Policies administrateur : seul un utilisateur présent dans admin_users peut modifier produits/commandes.
drop policy if exists "admins products insert" on public.products;
create policy "admins products insert" on public.products for insert
with check(exists(select 1 from public.admin_users a where a.user_id=auth.uid()));

drop policy if exists "admins products update" on public.products;
create policy "admins products update" on public.products for update
using(exists(select 1 from public.admin_users a where a.user_id=auth.uid()))
with check(exists(select 1 from public.admin_users a where a.user_id=auth.uid()));

drop policy if exists "admins products delete" on public.products;
create policy "admins products delete" on public.products for delete
using(exists(select 1 from public.admin_users a where a.user_id=auth.uid()));

drop policy if exists "admins orders update" on public.orders;
create policy "admins orders update" on public.orders for update
using(exists(select 1 from public.admin_users a where a.user_id=auth.uid()))
with check(exists(select 1 from public.admin_users a where a.user_id=auth.uid()));

drop policy if exists "admins orders read all" on public.orders;
create policy "admins orders read all" on public.orders for select
using(auth.uid()=user_id or exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
