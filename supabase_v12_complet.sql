create table if not exists public.payment_transactions (
 id bigint generated by default as identity primary key,
 order_id bigint not null references public.orders(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 provider text not null check (provider in ('wave','orange_money','mtn_momo','cash')),
 amount numeric(12,2) not null check (amount >= 0),
 currency text not null default 'XOF',
 status text not null default 'pending' check (status in ('pending','paid','failed','cancelled')),
 provider_reference text,
 created_at timestamptz not null default now(),
 paid_at timestamptz
);

alter table public.payment_transactions enable row level security;
drop policy if exists "payments own read" on public.payment_transactions;
drop policy if exists "payments own insert" on public.payment_transactions;
drop policy if exists "admin payments read" on public.payment_transactions;
